import sharp from 'sharp'
import fs from 'node:fs/promises'

const INPUT =
  'public/branding/texas-oem-parts-tag-logo.png'

const OUTPUT =
  'src/lib/zebraLogo.ts'

const TARGET_WIDTH = 560

const source = sharp(INPUT)

const metadata = await source.metadata()

if (!metadata.width || !metadata.height) {
  throw new Error('Unable to read logo dimensions.')
}

const targetHeight = Math.round(
  TARGET_WIDTH * (metadata.height / metadata.width),
)

const { data, info } = await sharp(INPUT)
  .resize({
    width: TARGET_WIDTH,
    height: targetHeight,
    fit: 'fill',
  })
  .flatten({ background: '#ffffff' })
  .grayscale()
  .threshold(175)
  .raw()
  .toBuffer({ resolveWithObject: true })

const width = info.width
const height = info.height
const bytesPerRow = Math.ceil(width / 8)
const totalBytes = bytesPerRow * height

const packed = Buffer.alloc(totalBytes)

for (let y = 0; y < height; y += 1) {
  for (let x = 0; x < width; x += 1) {
    const pixel = data[y * width + x]

    // ZPL: 1 = black dot, 0 = white dot
    if (pixel < 128) {
      const byteIndex =
        y * bytesPerRow + Math.floor(x / 8)

      const bit =
        7 - (x % 8)

      packed[byteIndex] |= 1 << bit
    }
  }
}

const hex =
  packed.toString('hex').toUpperCase()

const zpl =
  `^GFA,${totalBytes},${totalBytes},${bytesPerRow},${hex}`

const output = `// AUTO-GENERATED by scripts/build-zebra-logo.mjs
// Source: ${INPUT}
// Zebra graphic size: ${width} x ${height} dots

export const TEXAS_OEM_ZEBRA_LOGO_WIDTH = ${width}
export const TEXAS_OEM_ZEBRA_LOGO_HEIGHT = ${height}

export const TEXAS_OEM_ZEBRA_LOGO = ${JSON.stringify(zpl)}
`

await fs.writeFile(
  OUTPUT,
  output,
  'utf8',
)

console.log(
  `Generated ${OUTPUT}: ${width}x${height}, ${totalBytes} bytes`,
)
